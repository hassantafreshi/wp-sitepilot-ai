<?php
declare(strict_types=1);
namespace AISAAutoPilot\Support;

class PdfExporter {
	public function export_html( array $messages, string $title = 'Chat History' ): string {
		$blog  = get_bloginfo( 'name' );
		$url   = get_site_url();
		$date  = gmdate( 'Y-m-d H:i T' );
		$color = '#202a8d';
		$msgs  = '';
		foreach ( $messages as $m ) {
			$r = 'user' === ( $m['role'] ?? 'user' ) ? 'User' : 'AI';
			$c = nl2br( esc_html( $m['content'] ?? '' ) );
			// Logical margins, so the visitor's bubble stays on the reading-end
			// side of an RTL transcript instead of being mirrored to the wrong one.
			$msgs .= '<div style="margin:12px 0;padding:12px 16px;border-radius:8px;max-width:80%;' . ( 'User' === $r ? 'margin-inline-start:auto;background:#eef2ff;' : 'margin-inline-end:auto;background:#f3f4f6;' ) . "\"><strong style=\"font-size:11px;color:{$color};\">{$r}</strong><p style=\"margin:4px 0 0;font-size:14px;line-height:1.6;\">{$c}</p></div>";
		}

		$lang = str_replace( '_', '-', get_locale() );
		$dir  = is_rtl() ? 'rtl' : 'ltr';

		return '<!DOCTYPE html><html lang="' . esc_attr( $lang ) . '" dir="' . esc_attr( $dir ) . '"><head><meta charset="utf-8"><style>
			@media print{body{font-size:12pt;}h1{font-size:18pt;}.no-print{display:none;}}
			body{max-width:640px;margin:0 auto;padding:40px 20px;font-family:system-ui,-apple-system,sans-serif;color:#1f2937;background:white;}
			.header{border-bottom:2px solid ' . $color . ';padding-bottom:16px;margin-bottom:24px;}
			h1{margin:0;font-size:22px;color:' . $color . ';}
			.meta{font-size:12px;color:#6b7280;margin-top:4px;}
			.footer{margin-top:32px;padding-top:16px;border-top:1px solid #e5e7eb;font-size:11px;color:#9ca3af;text-align:center;}
		</style></head><body>
		<div class="header"><h1>' . esc_html( $title ) . '</h1>
		<p class="meta">' . esc_html( $blog ) . ' &middot; ' . esc_html( $date ) . ' &middot; ' . esc_html( $url ) . '</p></div>
		' . $msgs . '
		<div class="footer">Generated by AI Site Assistant AutoPilot &middot; ' . esc_html( $date ) . '</div>
		<p class="no-print" style="margin-top:20px;"><button onclick="window.print()" style="padding:8px 20px;background:' . $color . ';color:white;border:none;border-radius:6px;cursor:pointer;">Save as PDF</button></p>
		</body></html>';
	}

	public function export_text( array $messages ): string {
		$text = '';foreach ( $messages as $m ) {
			// Plain text for Telegram and SMS; each channel escapes for its own format.
			$r     = ( $m['role'] ?? 'user' ) === 'user' ? 'User' : 'AI';
			$text .= $r . ': ' . (string) ( $m['content'] ?? '' ) . "\n\n";
		}return trim( $text );
	}

	public function export_word_by_word( array $messages ): string {
		$text = '';foreach ( $messages as $m ) {
			$r     = ( $m['role'] ?? 'user' ) === 'user' ? 'User' : 'AI';
			$words = preg_split( '/\s+/', wp_strip_all_tags( $m['content'] ?? '' ) );
			$line  = $r . ': ';
			foreach ( $words as $w ) {
				$line .= $w . ' ';}
			$text .= trim( $line ) . "\n\n";
		}return trim( $text );
	}
}
