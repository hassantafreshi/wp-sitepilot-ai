<?php
declare(strict_types=1);

namespace SitePilot\Support;

/**
 * Chat history PDF/HTML export for human handoff.
 * Generates a clean HTML page printable as PDF.
 */
class PdfExporter {

	public function export_html( array $messages, string $title = 'Chat History' ): string {
		if ( empty( $messages ) ) {
			return '<p>No messages to export.</p>';
		}

		$html = '<!DOCTYPE html><html><head><meta charset="UTF-8">';
		$html .= '<title>' . esc_html( $title ) . '</title>';
		$html .= '<style>
			*{margin:0;padding:0;box-sizing:border-box;}
			body{font-family:-apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif;
			    max-width:800px;margin:40px auto;padding:20px;color:#1a1a1a;background:#fff;}
			h1{font-size:24px;margin-bottom:8px;color:#4f46e5;}
			.meta{font-size:13px;color:#6b7280;margin-bottom:24px;border-bottom:2px solid #eef2ff;padding-bottom:12px;}
			.msg{margin-bottom:16px;padding:12px 16px;border-radius:12px;line-height:1.6;}
			.msg.user{margin-left:40px;background:#eef2ff;border:1px solid #c7d2fe;}
			.msg.assistant{margin-right:40px;background:#f9fafb;border:1px solid #e5e7eb;}
			.msg .role{font-size:11px;font-weight:700;text-transform:uppercase;letter-spacing:0.5px;margin-bottom:4px;}
			.msg.user .role{color:#4f46e5;}
			.msg.assistant .role{color:#6b7280;}
			.sources{margin-top:8px;font-size:12px;color:#6b7280;}
			.sources a{color:#4f46e5;text-decoration:none;}
			.footer{margin-top:32px;padding-top:16px;border-top:1px solid #e5e7eb;
			    font-size:12px;color:#9ca3af;text-align:center;}
			@media print{body{margin:20px;}.msg{break-inside:avoid;}}
		</style></head><body>';
		$html .= '<h1>' . esc_html( $title ) . '</h1>';
		$html .= '<div class="meta">Exported: ' . gmdate( 'Y-m-d H:i:s \G\M\T' ) . ' | Messages: ' . count( $messages ) . '</div>';

		foreach ( $messages as $m ) {
			$role = $m['role'] ?? 'user';
			$content = esc_html( $m['content'] ?? '' );
			$sources = $m['sources'] ?? array();
			$html .= '<div class="msg ' . $role . '">';
			$html .= '<div class="role">' . ( 'user' === $role ? 'Visitor' : 'AI Assistant' ) . '</div>';
			$html .= '<div class="content">' . nl2br( $content ) . '</div>';
			if ( ! empty( $sources ) ) {
				$html .= '<div class="sources">Sources: ';
				$links = array();
				foreach ( $sources as $s ) {
					$url = $s['url'] ?? '';
					$title = $s['title'] ?? $url;
					$links[] = $url ? '<a href="' . esc_url( $url ) . '">' . esc_html( $title ) . '</a>' : esc_html( $title );
				}
				$html .= implode( ', ', $links ) . '</div>';
			}
			$html .= '</div>';
		}

		$html .= '<div class="footer">Generated by SitePilot AI — ' . gmdate( 'Y-m-d' ) . '</div>';
		$html .= '</body></html>';
		return $html;
	}

	public function export_text( array $messages ): string {
		$text = "Chat Export\n" . str_repeat( '=', 50 ) . "\nDate: " . gmdate( 'Y-m-d H:i:s T' ) . "\n\n";
		foreach ( $messages as $m ) {
			$text .= ( 'user' === ( $m['role'] ?? '' ) ? 'Visitor: ' : 'AI: ' ) . ( $m['content'] ?? '' ) . "\n\n";
		}
		return $text;
	}
}
