<?php
/**
 * Writes includes/Efb/EfbKnowledgeStrings.php from includes/Efb/efb-knowledge.json, so every help topic's title, answer,
 * the editor steps and the feature labels are ordinary gettext calls: WP-CLI make-pot finds them for the .pot, and
 * WordPress looks them up in the site's language at runtime. Run it after every edit of efb-knowledge.json:
 *
 *   php scripts/efb-knowledge-strings.php           write the file
 *   php scripts/efb-knowledge-strings.php --check   exit 1 when the file is out of date (tests/EfbKnowledgeStringsTest.php)
 *
 * Not part of the plugin package (developer tool, like compile-mo.php).
 */

declare(strict_types=1);

if ( 'cli' !== PHP_SAPI ) {
	exit( 1 );
}

/**
 * The generated PHP for a knowledge file.
 *
 * @param array<string,mixed> $data Decoded efb-knowledge.json.
 */
function aisa_knowledge_strings_php( array $data ): string {
	$quote = static fn ( string $text ): string => "'" . str_replace( array( '\\', "'" ), array( '\\\\', "\\'" ), $text ) . "'";
	$cases = array();
	$add   = static function ( string $key, string $text, string $comment ) use ( &$cases, $quote ): void {
		if ( '' === trim( $text ) ) {
			return;
		}
		$cases[] = "\t\t\tcase " . $quote( $key ) . ":\n"
			. "\t\t\t\t/* translators: {$comment} */\n"
			. "\t\t\t\treturn __( " . $quote( $text ) . ", 'ai-site-assistant-autopilot' );\n";
	};
	foreach ( (array) ( $data['ui_pattern'] ?? array() ) as $key => $text ) {
		$add( 'ui.' . $key, (string) $text, 'A step of an Easy Form Builder how-to answer; keep the quoted names of buttons and panels as Easy Form Builder shows them in your language.' );
	}
	foreach ( (array) ( $data['entries'] ?? array() ) as $entry ) {
		$id = (string) ( $entry['id'] ?? '' );
		if ( '' === $id ) {
			continue;
		}
		$add( 'title.' . $id, (string) ( $entry['title'] ?? '' ), 'Title of an Easy Form Builder help topic in the AI assistant.' );
		$add( 'answer.' . $id, (string) ( $entry['answer'] ?? '' ), 'An Easy Form Builder how-to answer; keep the quoted names of settings and buttons as Easy Form Builder shows them in your language, and keep shortcodes, smart tags and plan names unchanged.' );
		foreach ( (array) ( $entry['features'] ?? array() ) as $feature => $label ) {
			$add( 'feature.' . $id . '.' . $feature, (string) $label, 'Name of an Easy Form Builder feature, followed by its state on this site (for example ": ready").' );
		}
	}

	return "<?php\n"
		. "// phpcs:disable Generic.Files.LineLength -- generated: long help texts stay on one line each.\n"
		. "declare(strict_types=1);\n\n"
		. "namespace AISAAutoPilot\\Efb;\n\n"
		. "/**\n"
		. " * GENERATED by scripts/efb-knowledge-strings.php from efb-knowledge.json: do not edit by hand.\n"
		. " *\n"
		. " * The help topics' texts as gettext calls, so they reach the .pot and are translated at runtime. EfbKnowledge asks\n"
		. " * for one text by key; only that one is looked up.\n"
		. " */\n"
		. "final class EfbKnowledgeStrings {\n\n"
		. "\t/** The translated text of a key (ui.*, title.<id>, answer.<id>, feature.<id>.<feature>), or null. */\n"
		. "\tpublic static function get( string \$key ): ?string {\n"
		. "\t\tswitch ( \$key ) {\n"
		. implode( '', $cases )
		. "\t\t}\n\n"
		. "\t\treturn null;\n"
		. "\t}\n"
		. "}\n";
}

$aisa_root   = dirname( __DIR__ );
$aisa_json   = json_decode( (string) file_get_contents( $aisa_root . '/includes/Efb/efb-knowledge.json' ), true );
$aisa_target = $aisa_root . '/includes/Efb/EfbKnowledgeStrings.php';
if ( ! is_array( $aisa_json ) ) {
	fwrite( STDERR, "efb-knowledge.json is not valid JSON.\n" );
	exit( 1 );
}
$aisa_php = aisa_knowledge_strings_php( $aisa_json );
if ( in_array( '--check', $argv, true ) ) {
	$aisa_same = is_file( $aisa_target ) && (string) file_get_contents( $aisa_target ) === $aisa_php;
	echo $aisa_same ? "EfbKnowledgeStrings.php is up to date.\n" : "EfbKnowledgeStrings.php is out of date: run php scripts/efb-knowledge-strings.php\n";
	exit( $aisa_same ? 0 : 1 );
}
file_put_contents( $aisa_target, $aisa_php );
echo 'Wrote ' . $aisa_target . "\n";
